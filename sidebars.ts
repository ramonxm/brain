import type { SidebarsConfig } from "@docusaurus/plugin-content-docs";

// Each top-level navbar section has its own sidebar, generated from its folder.
// A new note shows up on its own: no need to register it here.
//
// - Order: `sidebar_position` in the doc frontmatter. Docs without it go last,
//   in alphabetical order.
// - Subfolders become categories, configured by their `_category_.json`. The
//   category `key` keeps the i18n translation keys stable — see
//   i18n/en/docusaurus-plugin-content-docs/current.json.
// - Files and folders starting with `_` (`_inbox/`, `_templates/`) are ignored.

const section = (dirName: string): SidebarsConfig[string] => [
  { type: "autogenerated", dirName },
];

const sidebars: SidebarsConfig = {
  conceptsSidebar: section("concepts"),
  dataStructuresSidebar: section("data-structures"),
  algorithmsSidebar: section("algorithms"),
  topicsSidebar: section("topics"),
};

export default sidebars;
